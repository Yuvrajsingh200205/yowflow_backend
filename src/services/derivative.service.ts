import { promises as fs } from 'fs';
import path from 'path';
import sharp from 'sharp';
import { GalleryDerivativeKind, StorageProvider } from '@prisma/client';
import { prisma } from '../config/prisma';
import { env } from '../config/env';
import { logger } from '../config/logger';
import { buildObjectKey, createSignedUrl, createUploadUrl, getStorageProvider, localObjectPath } from './storage.service';

/**
 * Thumbnails and previews for gallery photographs. A wedding gallery is
 * hundreds of multi-megabyte originals; the grid must never load those, so each
 * image gets a small WebP thumbnail and a larger WebP preview. The original is
 * only ever fetched for an explicit, permitted download.
 */
export const DERIVATIVE_SPECS: Record<'THUMBNAIL' | 'PREVIEW', { width: number; quality: number }> = {
  THUMBNAIL: { width: 480, quality: 72 },
  PREVIEW: { width: 1600, quality: 78 },
};
const MAX_SOURCE_BYTES = 60 * 1024 * 1024;

type StoredFile = { id: string; objectKey: string; bucket: string; storageProvider: StorageProvider };

/** Reads an object's bytes from whichever storage provider holds it. */
export async function readObject(file: StoredFile): Promise<Buffer> {
  if (file.storageProvider === 'DATABASE') {
    const row = await prisma.fileObject.findUnique({ where: { id: file.id }, select: { content: true } });
    if (!row?.content) throw new Error('Stored content is missing');
    return Buffer.from(row.content);
  }
  if (file.storageProvider === 'LOCAL') {
    const target = localObjectPath(file.objectKey);
    if (!target) throw new Error('Invalid object key');
    return fs.readFile(target);
  }
  const res = await fetch(createSignedUrl(file.objectKey, file.bucket).url);
  if (!res.ok) throw new Error(`Storage read failed (${res.status})`);
  return Buffer.from(await res.arrayBuffer());
}

/** Writes generated bytes with the active provider and registers the FileObject. */
async function writeObject(input: { organizationId: string; projectId: string | null; originalName: string; mimeType: string; bytes: Buffer }) {
  const provider = getStorageProvider();
  const bucket = env.STORAGE_BUCKET;
  const objectKey = buildObjectKey(input.organizationId, 'GALLERY_DERIVATIVE', input.originalName);
  if (provider === 'LOCAL') {
    const target = localObjectPath(objectKey);
    if (!target) throw new Error('Invalid object key');
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, input.bytes);
  } else if (provider !== 'DATABASE') {
    const res = await fetch(createUploadUrl(objectKey, bucket).url, { method: 'PUT', body: new Uint8Array(input.bytes), headers: { 'content-type': input.mimeType } });
    if (!res.ok) throw new Error(`Storage write failed (${res.status})`);
  }
  return prisma.fileObject.create({
    data: {
      organizationId: input.organizationId,
      projectId: input.projectId,
      entityType: 'GALLERY_DERIVATIVE',
      storageProvider: provider,
      bucket,
      objectKey,
      originalName: input.originalName,
      mimeType: input.mimeType,
      sizeBytes: BigInt(input.bytes.byteLength),
      isRegistered: true,
      ...(provider === 'DATABASE' ? { content: Uint8Array.from(input.bytes) } : {}),
    },
    select: { id: true },
  });
}

const orientationOf = (w: number, h: number) => (Math.abs(w - h) / Math.max(w, h) < 0.04 ? 'SQUARE' : w > h ? 'LANDSCAPE' : 'PORTRAIT') as 'SQUARE' | 'LANDSCAPE' | 'PORTRAIT';

/**
 * Creates the missing derivatives for one image and records its true
 * dimensions (so the portal can lay out a stable masonry grid). Never throws:
 * a photograph without derivatives still works, it is just served at full size.
 */
export async function generateImageDerivatives(mediaId: string): Promise<{ generated: number }> {
  if (env.GALLERY_DERIVATIVES === 'off') return { generated: 0 };
  try {
    const media = await prisma.galleryMedia.findUnique({
      where: { id: mediaId },
      select: {
        id: true, organizationId: true, mediaType: true, title: true, width: true,
        gallery: { select: { projectId: true } },
        file: { select: { id: true, objectKey: true, bucket: true, storageProvider: true, sizeBytes: true, mimeType: true } },
        derivatives: { select: { kind: true } },
      },
    });
    if (!media || media.mediaType !== 'IMAGE' || Number(media.file.sizeBytes) > MAX_SOURCE_BYTES) return { generated: 0 };
    const have = new Set(media.derivatives.map((d) => d.kind));
    const wanted = (Object.keys(DERIVATIVE_SPECS) as Array<keyof typeof DERIVATIVE_SPECS>).filter((k) => !have.has(k));
    if (wanted.length === 0 && media.width) return { generated: 0 };

    const source = await readObject(media.file);
    const base = sharp(source, { failOn: 'none' }).rotate();
    const meta = await base.clone().metadata();

    let generated = 0;
    for (const kind of wanted) {
      const spec = DERIVATIVE_SPECS[kind];
      const { data, info } = await base.clone().resize({ width: spec.width, withoutEnlargement: true }).webp({ quality: spec.quality }).toBuffer({ resolveWithObject: true });
      const stored = await writeObject({ organizationId: media.organizationId, projectId: media.gallery.projectId, originalName: `${kind.toLowerCase()}-${media.id}.webp`, mimeType: 'image/webp', bytes: data });
      await prisma.galleryMediaDerivative.upsert({
        where: { mediaId_kind: { mediaId: media.id, kind: kind as GalleryDerivativeKind } },
        create: { mediaId: media.id, kind: kind as GalleryDerivativeKind, fileId: stored.id, width: info.width, height: info.height },
        update: { fileId: stored.id, width: info.width, height: info.height },
      });
      generated += 1;
    }
    // EXIF-rotated dimensions are the ones the viewer sees.
    const rotated = meta.orientation && meta.orientation >= 5;
    const w = (rotated ? meta.height : meta.width) ?? null;
    const h = (rotated ? meta.width : meta.height) ?? null;
    if (w && h && !media.width) await prisma.galleryMedia.update({ where: { id: media.id }, data: { width: w, height: h, orientation: orientationOf(w, h) } });
    return { generated };
  } catch (error) {
    logger.warn({ err: error, mediaId }, 'could not generate gallery derivatives');
    return { generated: 0 };
  }
}
